"""406. 根据身高重建队列（Queue Reconstruction by Height）

题目：假设有打乱顺序的一群人站成一排，每个人用整数对 (h, k) 表示，其中 h 是身高，k 是
这个人前面身高大于或等于 h 的人数。请重建这个队列，使每个人都满足自己的 k 值。

思路（贪心：高个子先站，按 k 插空位）：
    身高高的人能「看见」的人更多，也更不受矮个子影响，所以先安排高个子：
      1. 先把所有人按身高 h 从大到小排序；身高相同时，按 k 从小到大排序；
      2. 依次处理每个人，把它插入到结果队列中下标为 k 的位置。
    这样安排后，每个人前面的位置已经被「身高 >= 自己」的人占好（因为比矮的先处理、更高或
    一样高的排前面），插入下标 k 后，恰好有 k 个不矮于他的人在他前面；而后面插入的矮个子
    无论插在他前面还是后面，都不会影响他的 k（矮个子不算在「>= h」里）。

    为什么身高相同时按 k 升序：身高一样的人互相算「>=」。k 小的应该排在前面，若先插 k 大
    的，后插 k 小的会把它挤到更后面，位置关系就乱了；按 k 升序处理、并依次插入 k 处，正好
    让 k 小的靠前，符合要求。

    为什么「插入到下标 k」可行：往列表中间插入会把后面的元素整体后移，后移的那些人要么更高
    （不影响前排计数）要么是还没处理的矮个子（尚未入队）。所以这一步插入总能精确地为当前
    这个人腾出 k 个「身高 >= h」的前缀。

复杂度：时间 O(n^2)（每次插入是 O(n)，共 n 次），空间 O(n)。
"""


def reconstruct_queue(people):
    people.sort(key=lambda x: (-x[0], x[1]))
    result = []
    for person in people:
        result.insert(person[1], person)
    return result


if __name__ == "__main__":
    got = reconstruct_queue([[7, 0], [4, 4], [7, 1], [5, 0], [6, 1], [5, 2]])
    want = [[5, 0], [7, 0], [5, 2], [6, 1], [4, 4], [7, 1]]
    assert got == want
    got2 = reconstruct_queue([[6, 0], [5, 0], [4, 0], [3, 2], [2, 2], [1, 4]])
    want2 = [[4, 0], [5, 0], [2, 2], [3, 2], [1, 4], [6, 0]]
    assert got2 == want2
    assert reconstruct_queue([]) == []
    print("queue_reconstruction_by_height: all tests passed")

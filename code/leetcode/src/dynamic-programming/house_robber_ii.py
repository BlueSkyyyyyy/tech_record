"""213. 打家劫舍 II（House Robber II）

题目：你是一个专业的小偷，计划偷窃沿街的房屋，每间房内都藏有一定的现金。
这个地方所有的房屋都围成一圈，这意味着第一间房屋和最后一间房屋是相邻的。
相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被闯入，
系统会自动报警。给定一个代表每个房屋存放金额的非负整数数组，
计算你在不触动警报的情况下，一夜之内能够偷窃到的最高金额。

思路（动态规划：把「环」拆成两个「线」）：
    与 198 的区别只有一处：首尾相邻，不能同时偷第一间和最后一间。
    于是最优方案必然属于下面两种之一：
      - 不偷最后一间：问题退化成对 nums[0..n-2] 做 198；
      - 不偷第一间：问题退化成对 nums[1..n-1] 做 198。
    两者取最大即可。任何一种合法方案都不会同时偷首尾，因此一定被这两种
    情形覆盖，不会漏解。

    特殊情况：只有一间房时没有「相邻」可言，直接返回它的金额（否则会把
    两个空区间都算成 0）。n == 0 返回 0。

    为什么「拆环」是通法：环形约束往往可以靠在某个位置「剪一刀」，把环
    展成线，再枚举「这一刀两边分别缺席」的少数几种情况。这里剪在首尾之间，
    恰好只有两种情况。

复杂度：时间 O(n)（两趟线性扫描），空间 O(1)。
"""


def rob(nums):
    if len(nums) == 1:
        return nums[0]

    def rob_range(lo, hi):
        prev2, prev1 = 0, 0
        for i in range(lo, hi):
            prev2, prev1 = prev1, max(prev1, prev2 + nums[i])
        return prev1

    n = len(nums)
    return max(rob_range(0, n - 1), rob_range(1, n))


if __name__ == "__main__":
    assert rob([2, 3, 2]) == 3
    assert rob([1, 2, 3, 1]) == 4
    assert rob([1, 2, 3]) == 3
    assert rob([5]) == 5
    assert rob([]) == 0
    assert rob([1, 2, 1, 1]) == 3
    print("house_robber_ii: all tests passed")

"""198. 打家劫舍（House Robber）

题目：你是一个专业的小偷，计划偷窃沿街的房屋，每间房内都藏有一定的现金。
相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被闯入，
系统会自动报警。给定一个代表每个房屋存放金额的非负整数数组，
计算你在不触动警报的情况下，一夜之内能够偷窃到的最高金额。

思路（动态规划：在「选 / 不选」之间取最优）：
    设 dp[i] 表示只考虑前 i+1 间房（下标 0..i）能偷到的最大金额。对第 i 间房：
      - 偷它：就不能偷第 i-1 间，收益是 dp[i-2] + nums[i]；
      - 不偷它：收益等于只考虑前 i-1 间的结果 dp[i-1]。
    两者取最大：

        dp[i] = max(dp[i-1], dp[i-2] + nums[i])

    为什么这样不重不漏：任何最优方案对最后一间房要么偷、要么不偷，两种情况
    互斥且穷尽；「偷」时第 i-1 间必然不偷，正好可以用 dp[i-2] 承接。

    初始化 dp[-1] = dp[-2] = 0（没有房子时收益为 0），从前往后递推。
    只依赖前两项，用两个滚动变量即可把空间压到 O(1)。

    这道题是「决策型 DP」的入门：状态里没有增量（房子是离散的），核心是
    每次在「当前这步做还是不做」之间取更优。

复杂度：时间 O(n)，空间 O(1)。
"""


def rob(nums):
    prev2, prev1 = 0, 0
    for x in nums:
        prev2, prev1 = prev1, max(prev1, prev2 + x)
    return prev1


if __name__ == "__main__":
    assert rob([1, 2, 3, 1]) == 4
    assert rob([2, 7, 9, 3, 1]) == 12
    assert rob([]) == 0
    assert rob([5]) == 5
    assert rob([2, 1, 1, 2]) == 4
    print("house_robber: all tests passed")
